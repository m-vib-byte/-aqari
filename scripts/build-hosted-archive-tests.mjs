// Prepare source-controlled, rollback-only SQL acceptance in a separate workspace.
// This script has no database connection and never accepts a URL or credential.
import fs from 'node:fs/promises';
const suites=['unit_meter_readings','financial_archive','official_document_source_binding','official_document_pdf_archive','workspace_feature_discovery'];
const slug='aqari-v267-archive-acceptance-20260912';
const id='7f6b0000-0000-4000-8000-000000000098';
for(const suite of suites){
 let source=await fs.readFile(new URL('../staging-database/tests/'+suite+'.sql',import.meta.url),'utf8');
 if(!/^begin;$/m.test(source)||!/rollback;/i.test(source)||/\bcommit\s*;/i.test(source))throw Error('Expected rollback-only test: '+suite);
 if(!source.includes("'aqari-v267-staging'"))throw Error('Expected source workspace marker: '+suite);
 source=source.replaceAll("'aqari-v267-staging'", "'"+slug+"'");
 source=source.replace(/^begin;$/m,`begin;
set local statement_timeout='30s';
set local lock_timeout='3s';
insert into public.aqari_workspaces(id,slug,name) values('${id}','${slug}','اختبار أرشفة مؤقت — يتراجع بالكامل');
insert into public.aqari_app_state(workspace_id,payload) values('${id}','{}');`);
 // The archive/meter suites are not readiness tests. Their synthetic units have
 // explicit fixture inspections before lease creation after readiness activation.
 const prefix=suite==='unit_meter_readings'?'76510000':suite==='financial_archive'?'76520000':'7f680000';
 source=source.replaceAll('insert into public.aqari_leases',`
  insert into private.aqari_unit_readiness(id,workspace_id,unit_id,revision,state,inspected_on,source_ref,reason,recorded_by)
  select gen_random_uuid(),u.workspace_id,u.id,1,'ready',current_date,'Synthetic acceptance fixture','Synthetic inspection for archive test',auth.uid()
  from public.aqari_units u where left(u.id::text,8)='${prefix}'
   and not exists(select 1 from private.aqari_unit_readiness r where r.workspace_id=u.workspace_id and r.unit_id=u.id);
insert into public.aqari_leases`);
 const header='-- Generated by scripts/build-hosted-archive-tests.mjs from the matching local suite.\n-- Independently verified test branch only. No owner workspace or password credentials.\n';
 const destination=new URL('../staging-database/hosted-test/'+suite+'.sql',import.meta.url);
 if(process.argv.includes('--check')){
  if(await fs.readFile(destination,'utf8')!==header+source)throw Error('Stale hosted test: '+suite);
 }else await fs.writeFile(destination,header+source);
}
console.log('Hosted archive SQL tests: '+suites.length+' prepared.');
