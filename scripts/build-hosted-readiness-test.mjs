fixture=fixture.replaceAll("'aqari-v267-staging'","'aqari-v267-readiness-acceptance-20260912'")
 .replaceAll(',false);',',true);').replace(/^set role authenticated;/mg,'set local role authenticated;');
const ddl=(await read('staging-database/sql/unit-readiness.sql')).replace(/^begin;$/m,'').replace(/^commit;$/m,'');
