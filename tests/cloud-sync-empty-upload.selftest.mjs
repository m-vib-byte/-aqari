import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const context = {user:{id:'user-1'},workspace:{id:'isolated-1'},membership:{is_active:true,user_id:'user-1',workspace_id:'isolated-1'}};
const state = new Map();
const storage = {getItem:key=>state.has(key)?state.get(key):null,setItem:(key,value)=>state.set(key,String(value))};
let writes=0, reads=0;
let cloudPayload = null;
const supabase = {context,loadAppState:async()=>{reads++;return {workspace_id:'isolated-1',revision:0,payload:cloudPayload};},saveAppState:async()=>{writes++;return {workspace_id:'isolated-1',revision:1};}};
const scope = {userId:'user-1',workspaceId:'isolated-1'};
const sandbox={window:{AQARI_SUPABASE:supabase},localStorage:storage,location:{origin:'https://preview.test',pathname:'/'}};
vm.runInNewContext(fs.readFileSync('cloud-sync.js','utf8'),sandbox,{filename:'cloud-sync.js'});
sandbox.window.AQARI_DATA_GATE.activate(context);
await assert.rejects(()=>sandbox.window.AQARI_CLOUD_SYNC.uploadLocal(), error=>error?.code==='AQARI_NO_LOCAL_DATA');
assert.equal(reads,0,'must reject empty data before even reading cloud');
assert.equal(writes,0,'must never write empty state');
sandbox.window.AQARI_DATA_GATE.write({properties:[{id:'test-only'}]});
await sandbox.window.AQARI_CLOUD_SYNC.uploadLocal();
assert.equal(writes,1,'nonempty fixture should preserve existing upload behavior');
cloudPayload = {properties:[{id:'cloud-preserved'}]};
await assert.rejects(()=>sandbox.window.AQARI_CLOUD_SYNC.uploadLocal(), error=>error?.code==='AQARI_CLOUD_NOT_EMPTY');
assert.equal(writes,1,'populated cloud must never be overwritten by manual upload');
cloudPayload = null;
const originalLoad = supabase.loadAppState;
supabase.loadAppState = async()=>({workspace_id:'another-workspace',revision:0,payload:null});
await assert.rejects(()=>sandbox.window.AQARI_CLOUD_SYNC.uploadLocal(), error=>error?.code==='AQARI_DATA_SCOPE_REQUIRED');
assert.equal(writes,1,'cross-workspace result must never allow a write');
supabase.loadAppState = originalLoad;
cloudPayload = {};
await assert.rejects(()=>sandbox.window.AQARI_CLOUD_SYNC.restoreCloudToLocal({overwrite:true}), error=>error?.code==='AQARI_EMPTY_CLOUD_RESTORE');
assert.equal(sandbox.window.AQARI_DATA_GATE.read().properties[0].id,'test-only','empty cloud must not erase local records');
cloudPayload = {properties:[{id:'restored-only'}]};
const conflict = await sandbox.window.AQARI_CLOUD_SYNC.restoreCloudToLocal();
assert.equal(conflict.conflicts[0],'aqari_v30','restore must warn before overwriting existing records');
assert.equal(sandbox.window.AQARI_DATA_GATE.read().properties[0].id,'test-only');
// Simulate staging activation from an empty cloud seed: existing local records survive.
sandbox.window.AQARI_PUBLIC_CONFIG = {supabaseUrl:'https://ofgmcsmxmdswlovsckqs.supabase.co'};
const activated = sandbox.window.AQARI_DATA_GATE.activate(context, {});
assert.equal(activated.properties[0].id,'test-only','empty staging seed must not replace local records');
assert.equal(sandbox.window.AQARI_DATA_GATE.read().properties[0].id,'test-only');
sandbox.window.AQARI_DATA_GATE.seal();
await assert.rejects(()=>sandbox.window.AQARI_CLOUD_SYNC.uploadLocal(),error=>error?.code==='AQARI_DATA_SCOPE_REQUIRED');
assert.equal(writes,1,'unauthenticated upload must not write');
console.log('PASS: blank upload/restore blocked; populated upload preserved; restore conflict and sealed scope protected (mocked only)');
